#!/usr/bin/env node
// Update the existing US instance; bootstrap and infrastructure changes are manual.
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync,copyFileSync,lstatSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const target='haqi-us1';
const publicURL='https://us1.gameserver.keepwork.com/ai-work-company/';
const args=process.argv.slice(2);
if(args.some(a=>!['--dry-run','--help'].includes(a)))throw Error('Use --dry-run or --help.');
if(args.includes('--help')){
  console.log(`Deploy current workspace to ${target}\n${publicURL}\nnpm run deploy:public          Test, build, upload, back up and restart\nnpm run deploy:public -- --dry-run  Test, build and package only; no SSH\nExisting runtime, service, Nginx and private configuration are preserved.`);
  process.exit(0);
}
function run(command,argv,options={}){
  const result=spawnSync(command,argv,{cwd:root,stdio:'inherit',...options});
  if(result.error)throw result.error;
  if(result.status!==0)throw Error(`${command} failed (${result.status})`);
  return result.stdout;
}
if(Number(process.versions.node.split('.')[0])!==24)throw Error('Node 24 is required.');
run('npm',['test']);
run('npm',['run','build:site']);
const revision=run('git',['rev-parse','--short=12','HEAD'],{stdio:['ignore','pipe','inherit'],encoding:'utf8'}).trim();
const release=new Date().toISOString().replace(/[-:.]/g,'')+'-'+revision;
const work=resolve(root,'tmp','deploy',release),stage=resolve(work,'source');
mkdirSync(stage,{recursive:true,mode:0o700});
const inventory=run('git',['ls-files','--cached','--others','--exclude-standard','-z'],{stdio:['ignore','pipe','inherit'],encoding:'utf8'}).split('\0').filter(Boolean);
const files=[...new Set(inventory)].filter(name=>/^(backend|site|admin|company|free|worker|consumer|cli|scripts|deploy|docs)\//.test(name)||['package.json','README.md'].includes(name));
const manifest={release,revision,source:'current workspace including uncommitted edits',files:{}};
for(const name of files){
  if(name.split('/').some(part=>part==='..'||(part.startsWith('.')&&part!=='.well-known'))||/\.(sqlite(?:-wal|-shm)?|db|pem|key|log)$/.test(name))throw Error(`Refusing unexpected release file: ${name}`);
  const source=resolve(root,name);
  // Tracked deletions are intentionally absent from the new release.
  let info;try{info=lstatSync(source);}catch(e){if(e.code==='ENOENT')continue;throw e;}
  if(!info.isFile()||info.isSymbolicLink())throw Error(`Only regular release files allowed: ${name}`);
  const dest=resolve(stage,name);mkdirSync(dirname(dest),{recursive:true});copyFileSync(source,dest);
  manifest.files[name]=createHash('sha256').update(readFileSync(source)).digest('hex');
}
// These HTML documents are generated by build:site and may be ignored by Git.
for(const name of ['business-model-analysis.html','autonomous-operation-plan.html']){
  const relative='docs/'+name,source=resolve(root,relative);copyFileSync(source,resolve(stage,relative));
  manifest.files[relative]=createHash('sha256').update(readFileSync(source)).digest('hex');
}
writeFileSync(resolve(stage,'release-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
const archive=resolve(work,'release.tar.gz');
run('tar',['-czf',archive,'-C',stage,'.'],{env:{...process.env,COPYFILE_DISABLE:'1',COPY_EXTENDED_ATTRIBUTES_DISABLE:'1'}});
const sha=createHash('sha256').update(readFileSync(archive)).digest('hex');
console.log(`Release: ${release}\nFiles: ${Object.keys(manifest.files).length}\nArchive: ${archive}\nSHA256: ${sha}`);
if(args.includes('--dry-run')){console.log('Dry run complete; server unchanged.');process.exit(0);}
// All interpolated remote arguments below are generated hex/alphanumeric identifiers.
run('ssh',['-o','BatchMode=yes','-o','ConnectTimeout=10',target,'test -f /etc/ai-work-company/service.env && test -x /opt/ai-work-company/runtime/node && test -L /opt/ai-work-company/current']);
run('scp',['-q',archive,`${target}:/opt/ai-work-company/releases/${release}.tar.gz`]);
run('ssh',['-o','BatchMode=yes',target,`python3 - ${release} ${sha}`],{input:readFileSync(resolve(root,'deploy/update-remote.py')),stdio:['pipe','inherit','inherit']});
run('curl',['--fail','--silent','--show-error','--max-time','30',publicURL+'health']);
console.log(`\nDeployed: ${publicURL}\nMarket: ${publicURL}company/\nVerify the Tasks link in a browser.`);
